// Abhivadanam in Telugu letters: the same parts as sandhya.js abhivadanam(). The person's own words
// (pravara rishis, gotram, name) stay as typed; sutra and sakha fall back to Telugu defaults.
const ARSHEYA = { 1: 'ఏకార్షేయ', 2: 'ద్వ్యార్షేయ', 3: 'త్ర్యార్షేయ', 5: 'పంచార్షేయ', 7: 'సప్తార్షేయ' };
export const SUTRA_TE = 'ఆపస్తంబ';
export const SAKHA_TE = 'యజుః';
export function abhivadanamTe(c = {}) {
  const v = (x) => ({ v: x });
  const rishis = (c.pravara || '').split(/[,\s]+/).filter(Boolean);
  const arsheya = ARSHEYA[rishis.length];
  return [
    'చతుస్సాగర పర్యంతం గో బ్రాహ్మణేభ్యః శుభం భవతు\n',
    v(rishis.length ? rishis.join(' ') : '____'), ' ', ...(arsheya ? [v(arsheya), ' '] : []), 'ప్రవరాన్విత, ',
    v(c.gotra || '____'), ' గోత్రః, ', v(c.sutra || SUTRA_TE), ' సూత్రః, ',
    v(c.sakha || SAKHA_TE), ' శాఖాధ్యాయీ, ', v(c.name || '____'), ' శర్మా అహం భో అభివాదయే',
  ];
}
